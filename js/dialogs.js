/* ---------- цель и журнал квестов ---------- */
RP.objective = function (G) {
  var f = G.flags;
  if (G.ending) return 'Игра пройдена. Ахтубинск спасён';
  if (!f.fTalkMama) return 'Поговори с мамой дома';
  if (!f.talkSonic) return 'Собери 10 сфер и найди Серого Соника';
  if (!f.boss_fog) return 'Победи Фога на поляне в лесу';
  if (!f.fPortal) return 'Активируй портал в лесу (нужно 50 сфер)';
  if (!f.boss_evil) return 'Победи Злого Соника и забери СФЕРНЫЙ КЛЮЧ';
  if (!f.boss_drone) return 'Уничтожь Дрон-Мастера на фабрике';
  if (!f.boss_queen) return 'Побей Королеву сфер за воротами';
  return 'Поговори с главным монитором на фабрике';
};

RP.questLog = function (G) {
  var f = G.flags, out = [];
  function add(title, active, done, hint) {
    if (done) out.push({ title: title, done: true, hint: hint });
    else if (active) out.push({ title: title, done: false, hint: hint });
  }
  add('Мамин приказ', f.fTalkMama && !f.talkSonic, f.talkSonic,
    'Собрать 10 красных сфер и поговорить с Серым Соником');
  add('Фог из леса', f.talkSonic && !f.boss_fog, f.boss_fog,
    'Добраться до поляны в лесу и победить Фога');
  add('Порталу нужно 50', f.boss_fog && !f.fPortal, f.fPortal,
    'Собрать 50 сфер и активировать портал на поляне');
  add('Злой Соник', f.fPortal && !f.boss_evil, f.boss_evil,
    'Пройти в измерение и победить Злого Соника');
  add('Красный пропуск', f.boss_fog && !G.keys.pass, G.keys.pass,
    'Забрать ПРОПУСК у поверженного Фога');
  add('Сферный ключ', f.boss_evil && !G.keys.key, G.keys.key,
    'Забрать СФЕРНЫЙ КЛЮЧ у Злого Соника');
  add('Дрон-Мастер', G.keys.key && !f.boss_drone, f.boss_drone,
    'Уничтожить Дрон-Мастера на фабрике');
  add('Королева сфер', f.boss_drone && !f.boss_queen, f.boss_queen,
    'Пройти за ворота и победить Королеву');
  add('Финальный монитор', f.boss_queen && !G.ending, G.ending,
    'Поговорить с монитором в глубине фабрики');

  /* побочные */
  add('Фотики Соника (Герман)', !f.germanDone, f.germanDone,
    'Собрать 5 фотиков Соника — награда: СФЕРНЫЙ ПИСТОЛЕТ');
  add('Белая жижа (Макс)', !f.maxDone, f.maxDone,
    'Принести Максу 3 белой жижи — награда: 25 сфер');
  add('Диплом профессора', !f.profDone, f.profDone,
    'Найти диплом на свалке и отдать профессору');
  var messDone = f.mess_m1 && f.mess_m2 && f.mess_m3 && f.mess_m4;
  add('Уборка у мамы', !messDone, messDone,
    'Собрать 4 кучи носков дома — награда: +1 сердечко');
  return out;
};

